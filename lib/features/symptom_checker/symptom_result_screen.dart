class SymptomResultScreen extends StatelessWidget {
  const SymptomResultScreen({super.key, required this.provider});

  final SymptomProvider provider;

  @override
  Widget build(BuildContext context) {
    final assessment = provider.assessment;

    if (assessment == null) {
      return const Center(
        child: CircularProgressIndicator(),
      );
    }

    return ListView(
      padding: const EdgeInsets.fromLTRB(
          AppSpacing.pageH, AppSpacing.lg, AppSpacing.pageH, AppSpacing.xxxl),
      children: [
        _TriageCard(assessment: assessment),
        const SizedBox(height: AppSpacing.lg),
        if (assessment.redFlags.isNotEmpty) ...[
          for (final flag in assessment.redFlags)
            Padding(
              padding: const EdgeInsets.only(bottom: AppSpacing.md),
              child: NoticeBanner(
                color: AppColors.danger,
                icon: Icons.emergency_rounded,
                title: 'Warning sign detected',
                message: flag,
              ),
            ),
          const NoticeBanner(
            color: AppColors.danger,
            icon: Icons.local_hospital_rounded,
            title: 'What to do now',
            message:
                'Do not self-medicate. Go to the nearest hospital or call an '
                'ambulance. Carry this screen with you so the doctor can see your '
                'reported symptoms.',
          ),
          const SizedBox(height: AppSpacing.lg),
        ],
        Text('Assessment summary', style: Theme.of(context).textTheme.titleMedium),
        const SizedBox(height: AppSpacing.sm),
        Text(assessment.advice,
            style: const TextStyle(fontSize: 13.5, height: 1.55)),
        const SizedBox(height: AppSpacing.lg),
        if (assessment.matches.isNotEmpty) ...[
          Text('Possible conditions',
              style: Theme.of(context).textTheme.titleMedium),
          const SizedBox(height: 4),
          Text(
            'Based on the symptoms you selected, in order of likelihood.',
            style: Theme.of(context).textTheme.bodySmall,
          ),
          const SizedBox(height: AppSpacing.md),
          for (final m in assessment.matches)
            Padding(
              padding: const EdgeInsets.only(bottom: AppSpacing.md),
              child: _ConditionCard(match: m),
            ),
        ],
        if (assessment.selfCare.isNotEmpty) ...[
          const SizedBox(height: AppSpacing.sm),
          Text('Self-care steps',
              style: Theme.of(context).textTheme.titleMedium),
          const SizedBox(height: AppSpacing.md),
          AppCard(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                for (final step in assessment.selfCare)
                  BulletPoint(
                    text: step,
                    color: AppColors.secondary,
                    icon: Icons.check_rounded,
                  ),
              ],
            ),
          ),
        ],
        const SizedBox(height: AppSpacing.lg),
        _RecommendedMedicines(assessment: assessment),
        const SizedBox(height: AppSpacing.lg),
        const NoticeBanner(
          color: AppColors.textTertiary,
          icon: Icons.info_rounded,
          message:
              'This assessment is generated by a rule-based clinical engine and '
              'is intended for education only. It is not a medical diagnosis. '
              'Please consult a doctor for a proper evaluation.',
        ),
        const SizedBox(height: AppSpacing.lg),
        Row(
          children: [
            Expanded(
              child: OutlinedButton.icon(
                onPressed: () {
                  provider.restartKeepingSymptoms();
                  Navigator.pushReplacement(
                    context,
                    MaterialPageRoute(
                        builder: (_) => const SymptomCheckerScreen()),
                  );
                },
                icon: const Icon(Icons.arrow_back_rounded, size: 18),
                label: const Text('Revise answers'),
              ),
            ),
            const SizedBox(width: AppSpacing.sm),
            Expanded(
              child: FilledButton.icon(
                onPressed: provider.reset,
                icon: const Icon(Icons.refresh_rounded, size: 18),
                label: const Text('New check'),
              ),
            ),
          ],
        ),
      ],
    );
  }
}

class _TriageCard extends StatelessWidget {
  const _TriageCard({required this.assessment});

  final Assessment assessment;

  @override
  Widget build(BuildContext context) {
    final level = assessment.level;

    return Container(
      padding: const EdgeInsets.all(AppSpacing.xl),
      decoration: BoxDecoration(
        color: level.color,
        borderRadius: BorderRadius.circular(AppRadius.lg),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Row(
            children: [
              Container(
                width: 40,
                height: 40,
                decoration: BoxDecoration(
                  color: Colors.white.withValues(alpha: 0.22),
                  shape: BoxShape.circle,
                ),
                child: Icon(level == TriageLevel.emergency
                    ? Icons.emergency_rounded
                    : Icons.medical_services_rounded,
                    color: Colors.white, size: 20),
              ),
              const SizedBox(width: AppSpacing.md),
              Expanded(
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Text(
                      level.label,
                      style: const TextStyle(
                        color: Colors.white,
                        fontSize: 20,
                        fontWeight: FontWeight.w700,
                      ),
                    ),
                    Text(
                      level.action,
                      style: TextStyle(
                        color: Colors.white.withValues(alpha: 0.9),
                        fontSize: 12.5,
                      ),
                    ),
                  ],
                ),
              ),
            ],
          ),
          const SizedBox(height: AppSpacing.lg),
          Row(
            children: [
              Text(
                'Severity score',
                style: TextStyle(
                  color: Colors.white.withValues(alpha: 0.85),
                  fontSize: 12,
                ),
              ),
              const Spacer(),
              Text(
                '${assessment.score} / 100',
                style: const TextStyle(
                  color: Colors.white,
                  fontSize: 14,
                  fontWeight: FontWeight.w700,
                ),
              ),
            ],
          ),
          const SizedBox(height: 6),
          ClipRRect(
            borderRadius: BorderRadius.circular(4),
            child: LinearProgressIndicator(
              value: assessment.score / 100,
              minHeight: 7,
              backgroundColor: Colors.white.withValues(alpha: 0.25),
              valueColor: AlwaysStoppedAnimation(Colors.white),
            ),
          ),
        ],
      ),
    );
  }
}

class _ConditionCard extends StatelessWidget {
  const _ConditionCard({required this.match});

  final ConditionMatch match;

  @override
  Widget build(BuildContext context) {
    final c = match.condition;
    final color = match.probability >= 60
        ? AppColors.warning
        : match.probability >= 35
            ? AppColors.info
            : AppColors.textTertiary;

    return AppCard(
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Row(
            children: [
              Expanded(
                child: Text(
                  c.name,
                  style: const TextStyle(fontSize: 14.5, fontWeight: FontWeight.w700),
                ),
              ),
              Container(
                padding:
                    const EdgeInsets.symmetric(horizontal: 8, vertical: 3),
                decoration: BoxDecoration(
                  color: color.withValues(alpha: 0.12),
                  borderRadius: AppRadius.pillRadius,
                ),
                child: Text(
                  '${match.probability}% match',
                  style: TextStyle(
                    fontSize: 11.5,
                    fontWeight: FontWeight.w700,
                    color: color,
                  ),
                ),
              ),
            ],
          ),
          const SizedBox(height: 6),
          Text(
            c.description,
            style: const TextStyle(
              fontSize: 12.5,
              height: 1.5,
              color: AppColors.textSecondary,
            ),
          ),
          const SizedBox(height: AppSpacing.md),
          ClipRRect(
            borderRadius: BorderRadius.circular(3),
            child: LinearProgressIndicator(
              value: match.probability / 100,
              minHeight: 5,
              backgroundColor: AppColors.surfaceAlt,
              valueColor: AlwaysStoppedAnimation(color),
            ),
          ),
          const SizedBox(height: AppSpacing.md),
          Wrap(
            spacing: 6,
            runSpacing: 6,
            children: [
              for (final s in match.matchedSymptoms)
                AppBadge(label: s, color: AppColors.textSecondary, dense: true),
            ],
          ),
          const SizedBox(height: AppSpacing.md),
          Text(
            'What usually helps',
            style: Theme.of(context).textTheme.labelMedium,
          ),
          const SizedBox(height: 6),
          for (final r in c.recommendations.take(3))
            BulletPoint(
              text: r,
              icon: Icons.tips_and_updates_rounded,
              color: AppColors.secondary,
            ),
          const SizedBox(height: AppSpacing.sm),
          const Divider(),
          const SizedBox(height: AppSpacing.sm),
          Row(
            children: [
              const Icon(Icons.schedule_rounded,
                  size: 15, color: AppColors.textTertiary),
              const SizedBox(width: 6),
              Text(
                'See a doctor within ${c.seeDoctorWithinHours} hours if it worsens',
                style: const TextStyle(
                    fontSize: 11.5, color: AppColors.textTertiary),
              ),
            ],
          ),
        ],
      ),
    );
  }
}

class _RecommendedMedicines extends StatelessWidget {
  const _RecommendedMedicines({required this.assessment});

  final Assessment assessment;

  @override
  Widget build(BuildContext context) {
    final categories = <String>{
      for (final m in assessment.matches) ...m.condition.overTheCounterCategories,
    }.toList();

    final meds = MockMedicines.all
        .where((m) => categories.contains(m.category) && m.otc)
        .take(4)
        .toList();

    if (meds.isEmpty) return const SizedBox.shrink();

    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Text('Over-the-counter options',
            style: Theme.of(context).textTheme.titleMedium),
        const SizedBox(height: 4),
        Text(
          'Commonly used for the symptoms you reported. Check with a '
          'pharmacist before buying.',
          style: Theme.of(context).textTheme.bodySmall,
        ),
        const SizedBox(height: AppSpacing.md),
        for (final m in meds)
          Padding(
            padding: const EdgeInsets.only(bottom: AppSpacing.sm),
            child: AppCard(
              onTap: () => Navigator.push(
                context,
                MaterialPageRoute(
                    builder: (_) => MedicineDetailScreen(medicine: m)),
              ),
              padding: const EdgeInsets.symmetric(
                  horizontal: AppSpacing.lg, vertical: AppSpacing.md),
              child: Row(
                children: [
                  Expanded(
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: [
                        Text(
                          m.name,
                          style: const TextStyle(
                              fontSize: 13.5, fontWeight: FontWeight.w700),
                        ),
                        Text(
                          '${m.genericName} ${m.strength} · ${m.category}',
                          style: const TextStyle(
                              fontSize: 11, color: AppColors.textTertiary),
                        ),
                      ],
                    ),
                  ),
                  AppBadge(label: 'OTC', color: AppColors.success, dense: true),
                  const SizedBox(width: AppSpacing.sm),
                  const Icon(Icons.chevron_right_rounded,
                      color: AppColors.textTertiary),
                ],
              ),
            ),
          ),
      ],
    );
  }
}
